import json
import os
import sqlite3

from checkslib.fixture import Fixture, git_repo, write

# The CLI: `render` writes TODO.md whole, with its header, and seals it at 0444.
CLI = """#!/usr/bin/env bash
cd "$(dirname "$0")" || exit 2
case "${1:-}" in
  render) rm -f TODO.md; printf '<!-- generated by store.sh render from data/app.db -->\\n# rows\\n' > TODO.md
          chmod a-w TODO.md ;;
  export) echo export ;;
  *) printf 'store.sh <verb>\\n\\n  render   write TODO.md\\n  export   write the export\\n' ;;
esac
"""
RENDER = "<!-- generated by store.sh render from data/app.db -->\n# rows\n"
DYNAMIC = {"kind": "dynamic", "schema_version": 2, "export": "export"}
STATIC = {"kind": "static", "producer": "store.sh render", "regen": ["store.sh", "render"]}


def _db(path, user_version):
    path.parent.mkdir(parents=True, exist_ok=True)
    con = sqlite3.connect(path)
    con.execute("CREATE TABLE rows (id INTEGER PRIMARY KEY)")
    con.execute(f"PRAGMA user_version = {int(user_version)}")
    con.commit()
    con.close()


def _repo(t, cli, todo, todo_mode, user_version):
    r = git_repo(t / "r", {"store.sh": CLI, ".gitignore": "data/\n", "cli.json": json.dumps(cli), "TODO.md": todo})
    os.chmod(r / "TODO.md", todo_mode)
    _db(r / "data" / "app.db", user_version)          # git-ignored, still a store on disk
    return r


# Every store classified and keeping its kind: the SQLite store at its
# declared version, TODO.md read-only, with its header, as `render` writes it.
def passing(t):
    cli = {"store": "data/app.db", "cli": "store.sh", "verbs": ["render", "export"], "renders": {"TODO.md": "render"},
           "kinds": {"data/app.db": DYNAMIC, "TODO.md": STATIC}}
    return Fixture(_repo(t, cli, RENDER, 0o444, 2))


# Every case at once: an undeclared SQLite file, a declared store with no
# kind, a dynamic JSON store, a SQLite store behind its declared version, and
# a hand-edited render (writable, no header, not what `render` writes).
def failing(t):
    cli = {"store": ["data/app.db", "todo.json", "notes.json"], "cli": "store.sh", "verbs": ["render", "export"],
           "renders": {"TODO.md": "render"},
           "kinds": {"data/app.db": DYNAMIC, "todo.json": dict(DYNAMIC, schema_version=1), "TODO.md": STATIC}}
    r = _repo(t, cli, "# rows, edited by hand\n", 0o644, 1)
    write(r / "todo.json", "{}\n")
    write(r / "notes.json", "{}\n")
    _db(r / "data" / "stray.db", 0)
    return Fixture(r, expect=[
        "lag: data/stray.db: store-shaped (a SQLite name) and named by neither",
        "lag: notes.json: declared (`store` entry `notes.json`) with no kind",
        "lag: todo.json: dynamic, but not a SQLite file",
        "lag: data/app.db: dynamic, PRAGMA user_version is 1 but cli.json's schema_version is 2",
        "lag: TODO.md: static, but writable (mode 0644)",
        "lag: TODO.md: static, but its first 2048 bytes do not name its producer `store.sh render`",
        "lag: TODO.md: static, regen `store.sh render` does not reproduce it (first difference at line 1)",
    ])
